            <h3>1. RTI Act, 2005</h3>

            <div class="card-body">

                <p>
                    The Right to Information Act, 2005 was passed by the Parliament of
                    India on 15 June 2005 and came into full force on 12 October 2005,
                    replacing the earlier Freedom of Information Act, 2002. The Act
                    extends to the whole of India and applies to all "public authorities,"
                    which includes bodies of self-government established under the
                    Constitution, and any authority or body owned, controlled, or
                    substantially financed by the Government.
                </p>

                <p>
                    Under the Act, every citizen has the right to request information from
                    a public authority, which is required to respond expeditiously — within
                    30 days for most requests, and within 48 hours where the information
                    concerns the life or liberty of a person. The Act also mandates that
                    every public authority computerize its records and proactively publish
                    various categories of information so as to minimize the need for
                    citizens to formally request it.
                </p>

                <p>
                    The Act establishes a three-tier structure for administering RTI
                    requests: the Public Information Officer (PIO) at the public authority
                    level, the First Appellate Authority for appeals against the PIO's
                    decision, and the State or Central Information Commission for second
                    appeals and complaints. It also prescribes penalties for PIOs who fail,
                    without reasonable cause, to furnish information within the specified
                    time or who provide incomplete, misleading, or false information.
                </p>

